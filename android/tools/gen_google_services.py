#!/usr/bin/env python3
"""Generate app/src/main/res/values/google_services.xml from app/google-services.json.

Equivalent to what the com.google.gms.google-services Gradle plugin generates, without
depending on the plugin (FirebaseInitProvider reads these resources at startup).
Re-run after replacing google-services.json.
"""
import json, os, sys
from xml.sax.saxutils import escape

here = os.path.dirname(os.path.abspath(__file__))
app = os.path.join(here, "..", "app")
cfg = json.load(open(os.path.join(app, "google-services.json")))
package = "io.github.sidd065.agentcompanion"
client = next((c for c in cfg["client"] if c["client_info"]["android_client_info"]["package_name"] == package), None)
if client is None:
    sys.exit(f"google-services.json has no Android client for {package}")
pi = cfg["project_info"]
values = {
    "google_app_id": client["client_info"]["mobilesdk_app_id"],
    "gcm_defaultSenderId": pi["project_number"],
    "google_api_key": client["api_key"][0]["current_key"],
    "google_crash_reporting_api_key": client["api_key"][0]["current_key"],
    "project_id": pi["project_id"],
}
if pi.get("storage_bucket"):
    values["google_storage_bucket"] = pi["storage_bucket"]
if pi.get("firebase_url"):
    values["firebase_database_url"] = pi["firebase_url"]
out = os.path.join(app, "src", "main", "res", "values", "google_services.xml")
with open(out, "w") as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_google_services.py from google-services.json. -->\n<resources>\n')
    for k, v in values.items():
        f.write(f'    <string name="{k}" translatable="false">{escape(str(v))}</string>\n')
    f.write("</resources>\n")
print("wrote", os.path.relpath(out, os.path.join(here, "..")), "for project", pi["project_id"])
