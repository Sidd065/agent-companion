package io.github.sidd065.agentcompanion.net

import com.google.crypto.tink.subtle.X25519
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.security.MessageDigest
import javax.crypto.AEADBadTagException
import javax.crypto.Cipher
import javax.crypto.Mac
import javax.crypto.spec.IvParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Initiator side of Noise_IK_25519_ChaChaPoly_SHA256 (and IKpsk1 for pairing),
 * as specified at https://noiseprotocol.org/noise.html and implemented by the
 * daemon with flynn/noise. The phone is always the initiator, so only the two
 * IK messages it writes/reads are implemented. Cross-checked against vectors
 * generated by the daemon (NoiseTest).
 */
object Noise {
    const val DH_LEN = 32
    const val TAG_LEN = 16
    const val MAX_MESSAGE = 65535

    class KeyPair(val privateKey: ByteArray, val publicKey: ByteArray)

    fun generateKeyPair(): KeyPair {
        val priv = X25519.generatePrivateKey()
        return KeyPair(priv, X25519.publicFromPrivate(priv))
    }

    fun publicFromPrivate(priv: ByteArray): ByteArray = X25519.publicFromPrivate(priv)

    fun dh(priv: ByteArray, pub: ByteArray): ByteArray = X25519.computeSharedSecret(priv, pub)

    internal fun sha256(vararg parts: ByteArray): ByteArray {
        val md = MessageDigest.getInstance("SHA-256")
        parts.forEach { md.update(it) }
        return md.digest()
    }

    private fun hmac(key: ByteArray, vararg data: ByteArray): ByteArray {
        val mac = Mac.getInstance("HmacSHA256")
        mac.init(SecretKeySpec(key, "HmacSHA256"))
        data.forEach { mac.update(it) }
        return mac.doFinal()
    }

    /** Noise HKDF with 2 or 3 outputs. */
    internal fun hkdf(ck: ByteArray, ikm: ByteArray, n: Int): List<ByteArray> {
        val temp = hmac(ck, ikm)
        val o1 = hmac(temp, byteArrayOf(1))
        val o2 = hmac(temp, o1, byteArrayOf(2))
        if (n == 2) return listOf(o1, o2)
        val o3 = hmac(temp, o2, byteArrayOf(3))
        return listOf(o1, o2, o3)
    }

    /** ChaCha20-Poly1305 with Noise's nonce encoding (4 zero bytes + LE64 counter). */
    internal object Aead {
        private val transformation: String by lazy {
            listOf("ChaCha20/Poly1305/NoPadding", "ChaCha20-Poly1305").first { name ->
                runCatching { Cipher.getInstance(name) }.isSuccess
            }
        }

        private fun nonce(n: Long): ByteArray =
            ByteBuffer.allocate(12).order(ByteOrder.LITTLE_ENDIAN).putInt(0).putLong(n).array()

        fun encrypt(key: ByteArray, n: Long, ad: ByteArray, plaintext: ByteArray): ByteArray {
            val c = Cipher.getInstance(transformation)
            c.init(Cipher.ENCRYPT_MODE, SecretKeySpec(key, "ChaCha20"), IvParameterSpec(nonce(n)))
            c.updateAAD(ad)
            return c.doFinal(plaintext)
        }

        fun decrypt(key: ByteArray, n: Long, ad: ByteArray, ciphertext: ByteArray): ByteArray {
            val c = Cipher.getInstance(transformation)
            c.init(Cipher.DECRYPT_MODE, SecretKeySpec(key, "ChaCha20"), IvParameterSpec(nonce(n)))
            c.updateAAD(ad)
            return c.doFinal(ciphertext)
        }
    }

    /** A transport cipher (one direction). Not thread-safe; callers serialize. */
    class CipherState(private val key: ByteArray?) {
        private var n = 0L

        fun encrypt(plaintext: ByteArray, ad: ByteArray = EMPTY): ByteArray {
            val k = key ?: return plaintext
            check(n != -1L) { "nonce exhausted" }
            return Aead.encrypt(k, n++, ad, plaintext)
        }

        fun decrypt(ciphertext: ByteArray, ad: ByteArray = EMPTY): ByteArray {
            val k = key ?: return ciphertext
            check(n != -1L) { "nonce exhausted" }
            val pt = Aead.decrypt(k, n, ad, ciphertext) // throws on a bad tag; n unchanged
            n++
            return pt
        }
    }

    private val EMPTY = ByteArray(0)

    /** Result of a completed handshake. */
    class Session(val send: CipherState, val recv: CipherState, val responderPayload: ByteArray, val handshakeHash: ByteArray)

    /**
     * Initiator handshake state for IK / IKpsk1.
     * `ephemeral` may be injected for tests; otherwise a fresh key is generated.
     */
    class Initiator(
        private val s: KeyPair,
        private val rs: ByteArray,
        prologue: ByteArray,
        private val psk: ByteArray? = null,
        private val ephemeral: KeyPair? = null,
    ) {
        private var h: ByteArray
        private var ck: ByteArray
        private var k: ByteArray? = null
        private var n = 0L
        private var e: KeyPair? = null

        init {
            require(rs.size == DH_LEN) { "bad responder key" }
            val name = ("Noise_IK" + (if (psk != null) "psk1" else "") + "_25519_ChaChaPoly_SHA256").toByteArray()
            h = if (name.size <= 32) name.copyOf(32) else sha256(name)
            ck = h.copyOf()
            mixHash(prologue)
            mixHash(rs) // pre-message: <- s
        }

        private fun mixHash(data: ByteArray) {
            h = sha256(h, data)
        }

        private fun mixKey(ikm: ByteArray) {
            val (newCk, tempK) = hkdf(ck, ikm, 2)
            ck = newCk
            k = tempK
            n = 0
        }

        private fun mixKeyAndHash(ikm: ByteArray) {
            val (newCk, tempH, tempK) = hkdf(ck, ikm, 3)
            ck = newCk
            mixHash(tempH)
            k = tempK
            n = 0
        }

        private fun encryptAndHash(pt: ByteArray): ByteArray {
            val key = k
            val ct = if (key == null) pt else Aead.encrypt(key, n++, h, pt)
            mixHash(ct)
            return ct
        }

        private fun decryptAndHash(ct: ByteArray): ByteArray {
            val key = k
            val pt = if (key == null) ct else Aead.decrypt(key, n++, h, ct)
            mixHash(ct)
            return pt
        }

        /** -> e, es, s, ss [, psk], payload */
        fun writeMessage1(payload: ByteArray): ByteArray {
            val eph = ephemeral ?: generateKeyPair()
            e = eph
            val out = java.io.ByteArrayOutputStream()
            out.write(eph.publicKey)
            mixHash(eph.publicKey)
            if (psk != null) mixKey(eph.publicKey) // PSK handshakes also MixKey(e)
            mixKey(dh(eph.privateKey, rs)) // es
            out.write(encryptAndHash(s.publicKey)) // s
            mixKey(dh(s.privateKey, rs)) // ss
            if (psk != null) mixKeyAndHash(psk) // psk1
            out.write(encryptAndHash(payload))
            val msg = out.toByteArray()
            check(msg.size <= MAX_MESSAGE)
            return msg
        }

        /** <- e, ee, se, payload; returns the transport ciphers. */
        fun readMessage2(msg: ByteArray): Session {
            val eph = e ?: error("message 1 not written")
            if (msg.size < DH_LEN + TAG_LEN) throw AEADBadTagException("short handshake message")
            val re = msg.copyOfRange(0, DH_LEN)
            mixHash(re)
            if (psk != null) mixKey(re)
            mixKey(dh(eph.privateKey, re)) // ee
            mixKey(dh(s.privateKey, re)) // se (initiator side)
            val payload = decryptAndHash(msg.copyOfRange(DH_LEN, msg.size))
            val (k1, k2) = hkdf(ck, EMPTY, 2)
            return Session(send = CipherState(k1), recv = CipherState(k2), responderPayload = payload, handshakeHash = h.copyOf())
        }
    }
}
