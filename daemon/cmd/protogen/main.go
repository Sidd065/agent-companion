func main() {
	outPath := flag.String("out", "../desktop/packages/protocol/src/generated.ts", "output TypeScript file")
	flag.Parse()

	nameByType := map[reflect.Type]string{}
	for _, nt := range exportedTypes {
		nameByType[nt.Type] = nt.Name
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by daemon/cmd/protogen. DO NOT EDIT.\n")
	buf.WriteString("// Source of truth: Go wire structs in daemon/internal/*.\n\n")
	buf.WriteString(fmt.Sprintf("export const PROTOCOL_VERSION = %d as const;\n\n", server.ProtocolVersion))
	capsJSON, _ := json.Marshal(server.Capabilities)
	buf.WriteString(fmt.Sprintf("export const SERVER_CAPABILITIES = %s as const;\n", string(capsJSON)))
	buf.WriteString("export type ServerCapability = (typeof SERVER_CAPABILITIES)[number];\n\n")

	for _, nt := range exportedTypes {
		buf.WriteString(fmt.Sprintf("export interface %s {\n", nt.Name))
		writeStructFields(&buf, nt.Type, nameByType)
		buf.WriteString("}\n\n")
	}

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("protogen: wrote %d interfaces to %s\n", len(exportedTypes), *outPath)
}

func writeStructFields(buf *bytes.Buffer, t reflect.Type, names map[reflect.Type]string) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		parts := strings.Split(tag, ",")
		jsonName := parts[0]
		omitEmpty := false
		for _, opt := range parts[1:] {
			if opt == "omitempty" {
				omitEmpty = true
			}
		}
		// Embedded structs flatten in encoding/json.
		if f.Anonymous && jsonName == "" {
			ft := f.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if ft.Kind() == reflect.Struct {
				writeStructFields(buf, ft, names)
				continue
			}
		}
		if jsonName == "" {
			jsonName = f.Name
		}
		optional := ""
		if omitEmpty || f.Type.Kind() == reflect.Pointer {
			optional = "?"
		}
		tsType := goTypeToTS(f.Type, names)
		buf.WriteString(fmt.Sprintf("  %s%s: %s;\n", jsonName, optional, tsType))
	}
}

var rawMsgType = reflect.TypeOf(json.RawMessage{})

func goTypeToTS(t reflect.Type, names map[reflect.Type]string) string {
	if t == rawMsgType {
		return "unknown"
	}
	if t.Kind() == reflect.Pointer {
		return goTypeToTS(t.Elem(), names) + " | null"
	}
	if name, ok := names[t]; ok {
		return name
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string" // base64 bytes
		}
		el := t.Elem()
		if el.Kind() == reflect.Pointer {
			el = el.Elem()
		}
		inner := goTypeToTS(el, names)
		if strings.Contains(inner, " | ") {
			return "(" + inner + ")[]"
		}
		return inner + "[]"
	case reflect.Map:
		return fmt.Sprintf("Record<string, %s>", goTypeToTS(t.Elem(), names))
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		// Anonymous inline struct
		var sb strings.Builder
		sb.WriteString("{ ")
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			if !f.IsExported() {
				continue
			}
			tag := f.Tag.Get("json")
			if tag == "-" {
				continue
			}
			parts := strings.Split(tag, ",")
			n := parts[0]
			if n == "" {
				n = f.Name
			}
			opt := ""
			for _, o := range parts[1:] {
				if o == "omitempty" {
					opt = "?"
				}
			}
			sb.WriteString(fmt.Sprintf("%s%s: %s; ", n, opt, goTypeToTS(f.Type, names)))
		}
		sb.WriteString("}")
		return sb.String()
	default:
		return "unknown"
	}
}
